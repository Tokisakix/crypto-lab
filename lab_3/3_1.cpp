void Mix_c(uint8_t * c){
    uint8_t t, u;
    for(int i = 0; i < 16; i+=4){
        t = c[i] ^ c[i + 1] ^ c[i + 2] ^ c[i + 3];
        u = c[i];
        c[i] ^= t ^ func_x(c[i] ^ c[i + 1]);
        c[i + 1] ^= t ^ func_x(c[i + 1] ^ c[i + 2]);
        c[i + 2] ^= t ^ func_x(c[i + 2] ^ c[i + 3]);
        c[i + 3] ^= t ^ func_x(c[i + 3] ^ u);
    }
    return;
}

uint32_t Sub_word(uint32_t x){
    uint8_t * p = reinterpret_cast<uint8_t *>(&x);
    for(int i = 0; i < 4; i++){
        p[i] = SBOX[p[i]];
    }
    return x;
}

void key_func(uint32_t * key, uint32_t * w){
    static uint32_t RCON[11] = {
        0, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
    };
    memcpy(w, key, 16);
    for(int i = 4; i < 44; i++){
        uint32_t temp = w[i - 1];
        if(i % 4 == 0){
            temp = (temp << 24) | (temp >> 8);
            temp = Sub_word(temp);
            temp = temp ^ RCON[i / 4];
        }
        w[i] = w[i - 4] ^ temp;
    }
    return;
}

